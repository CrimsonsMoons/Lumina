const vm=require('node:vm'),fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'..','library/blackjack/storage-bridge.js'),'utf8');
const events=[],handlers={},appends=[];
const parent={postMessage:(data)=>events.push(data)};
const window={parent,addEventListener:(name,fn)=>handlers[name]=fn};
const document={currentScript:{src:'https://site.test/library/blackjack/storage-bridge.js'},body:{append:(node)=>{appends.push(node.src);queueMicrotask(()=>node.onload())}},createElement:()=>({}),documentElement:{dataset:{}}};
const ctx=vm.createContext({window,document,URL,console,Object,Promise,Error});
vm.runInContext(source,ctx);
const api=vm.runInContext('LuminaLibraryStorage',ctx);
assert.equal(events.length,1);
